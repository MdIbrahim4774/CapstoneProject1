"""
ML5 prediction service.

Loads the trained ML3 XGBoost model and performs real
risk inference using the exact ML3 feature contract.
"""

from pathlib import Path

import joblib
import numpy as np

from src.api.schemas.network import (
    RiskPredictionRequest,
    RiskPredictionResponse,
)


MODEL_PATH = (
    Path(__file__).resolve().parents[2]
    / "ml"
    / "ml3_outputs"
    / "ml3_xgboost_model.joblib"
)

MODEL_VERSION = "ml3-xgboost-v1"

ML3_FEATURE_COLUMNS = [
    "avg_activity",
    "activity_growth",
    "active_hours",
    "peak_ratio",
    "variability",
    "internet_share",
    "hour_sin",
    "hour_cos",
]


def _load_model():
    """
    Load the trained ML3 model once when the service starts.
    """

    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"ML model artifact not found: {MODEL_PATH}"
        )

    try:
        return joblib.load(MODEL_PATH)
    except Exception as exc:
        raise RuntimeError(
            f"Failed to load ML model artifact: {MODEL_PATH}"
        ) from exc


MODEL = _load_model()


def _get_risk_level(risk_score: float) -> str:
    """
    Convert model probability into an operational risk level.
    """

    if risk_score >= 0.7:
        return "HIGH"

    if risk_score >= 0.4:
        return "MEDIUM"

    return "LOW"


def _build_feature_vector(
    request: RiskPredictionRequest,
) -> np.ndarray:
    """
    Build the exact eight-feature vector expected by ML3.
    """

    hour = request.feature_timestamp.hour

    hour_sin = np.sin(
        2 * np.pi * hour / 24
    )

    hour_cos = np.cos(
        2 * np.pi * hour / 24
    )

    return np.array(
        [[
            request.avg_activity,
            request.activity_growth,
            request.active_hours,
            request.peak_ratio,
            request.variability,
            request.internet_share,
            hour_sin,
            hour_cos,
        ]],
        dtype=float,
    )


def _get_top_features() -> list[str]:
    """
    Return the top contributing features when the model
    exposes feature_importances_.
    """

    if not hasattr(MODEL, "feature_importances_"):
        return []

    importances = np.asarray(
        MODEL.feature_importances_
    )

    if len(importances) != len(ML3_FEATURE_COLUMNS):
        return []

    ranked_indices = np.argsort(
        importances
    )[::-1]

    return [
        ML3_FEATURE_COLUMNS[index]
        for index in ranked_indices[:3]
        if importances[index] > 0
    ]


def predict_risk(
    request: RiskPredictionRequest,
) -> RiskPredictionResponse:
    """
    Generate a real risk prediction using the trained
    ML3 XGBoost model.
    """

    features = _build_feature_vector(request)

    try:
        if not hasattr(MODEL, "predict_proba"):
            raise RuntimeError(
                "Loaded model does not support probability prediction."
            )

        probabilities = MODEL.predict_proba(features)

        if probabilities.shape[1] < 2:
            raise RuntimeError(
                "Model does not provide binary class probabilities."
            )

        risk_score = float(
            probabilities[0][1]
        )

    except Exception as exc:
        raise RuntimeError(
            "ML model inference failed."
        ) from exc

    risk_score = float(
        np.clip(risk_score, 0.0, 1.0)
    )

    risk_level = _get_risk_level(
        risk_score
    )

    top_features = _get_top_features()

    if top_features:
        explanation_note = (
            "Risk prediction generated by the ML3 XGBoost model. "
            "Top model features: "
            + ", ".join(top_features)
            + "."
        )
    else:
        explanation_note = (
            "Risk prediction generated by the ML3 XGBoost model."
        )

    return RiskPredictionResponse(
        risk_score=risk_score,
        risk_level=risk_level,
        model_version=MODEL_VERSION,
        explanation_note=explanation_note,
    )